#!/usr/bin/env python3
"""Generate src/common/chunk_info_table.h: the flags every engine class's
GetChunkInfo returns for its chunk ids, by running those functions from
TmForeverFixed.exe (2.11.26, located via its PDB) under the Unicorn
emulator.

CMwNod::Archive (reading) uses the flags: 0xfacade01 = unknown chunk; bit 0
= parsed by Chunk(); bit 4 = stored skippable ("PIKS" + size). Knowing them
means the reader never has to peek ahead, which would decrypt a pack page
before the game has mixed node feedback into it.

  gen_chunk_info.py TmForeverFixed.exe TmForeverFixed.pdb > src/common/chunk_info_table.h
"""
import os
import sys

import pefile
from unicorn import UC_ARCH_X86, UC_MODE_32, Uc, UcError
from unicorn.x86_const import UC_X86_REG_EAX, UC_X86_REG_ECX, UC_X86_REG_EIP, UC_X86_REG_ESP

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "oracle"))
from sigmap import load_publics  # noqa: E402

UNKNOWN = 0xFACADE01
RETURN_MAGIC = 0x00001000
STACK_BASE = 0x00100000
STACK_SIZE = 0x00010000
OBJECT = 0x00200000

pe = pefile.PE(sys.argv[1])
base = pe.OPTIONAL_HEADER.ImageBase
size = (pe.OPTIONAL_HEADER.SizeOfImage + 0xFFF) & ~0xFFF
uc = Uc(UC_ARCH_X86, UC_MODE_32)
uc.mem_map(base, size)
uc.mem_write(base, pe.get_memory_mapped_image()[:size])
uc.mem_map(0, 0x2000)  # return trampoline page
uc.mem_map(STACK_BASE, STACK_SIZE)
uc.mem_map(OBJECT, 0x10000)  # zeroed fake "this"
uc.mem_map(0x7FFD0000, 0x10000)  # fs segment stand-in, if touched


def call(func, chunk_id):
    esp = STACK_BASE + STACK_SIZE - 0x100
    uc.mem_write(esp, RETURN_MAGIC.to_bytes(4, "little") + chunk_id.to_bytes(4, "little"))
    uc.reg_write(UC_X86_REG_ESP, esp)
    uc.reg_write(UC_X86_REG_ECX, OBJECT)
    uc.reg_write(UC_X86_REG_EAX, 0)
    try:
        uc.emu_start(func, RETURN_MAGIC, count=5000)
    except UcError:
        return None
    if uc.reg_read(UC_X86_REG_EIP) != RETURN_MAGIC:
        return None
    return uc.reg_read(UC_X86_REG_EAX)


# class name -> id, from the generated class tree
classes = {}
tree = os.path.join(os.path.dirname(__file__), "..", "..", "src", "common", "class_tree.h")
for line in open(tree):
    if line.strip().startswith("{0x"):
        parts = line.strip().strip("{},").split(", ")
        classes[parts[2].strip('"')] = int(parts[0], 16)

rows = []
failed = []
for name, locs in load_publics(sys.argv[2]).items():
    if not name.endswith("::GetChunkInfo"):
        continue
    cls = name[: -len("::GetChunkInfo")]
    if cls not in classes:
        continue
    sec, off = locs[0]
    func = base + pe.sections[sec - 1].VirtualAddress + off
    class_id = classes[cls]
    for low in range(0x1000):
        chunk = class_id | low
        info = call(func, chunk)
        if info is None:
            failed.append(chunk)
            continue
        if info != UNKNOWN:
            rows.append((chunk, info, cls))

# Second pass: GetChunkInfo is called on the node's actual class, also for
# ancestor chunk ids. Record where a class answers differently.
parent = {}
for line in open(tree):
    if line.strip().startswith("{0x"):
        parts = line.strip().strip("{},").split(", ")
        parent[int(parts[0], 16)] = int(parts[1], 16)
known = {}
for chunk, info, cls in rows:
    known.setdefault(chunk & 0xFFFFF000, []).append((chunk, info))
funcs = {}
for name, locs in load_publics(sys.argv[2]).items():
    if name.endswith("::GetChunkInfo") and name[:-14] in classes:
        sec, off = locs[0]
        funcs[classes[name[:-14]]] = base + pe.sections[sec - 1].VirtualAddress + off
overrides = []
for cid, func in funcs.items():
    anc = parent.get(cid, 0)
    while anc:
        for chunk, info in known.get(anc, []):
            got = call(func, chunk)
            if got is not None and got != info:
                overrides.append((cid, chunk, got))
        anc = parent.get(anc, 0)
print(f"# {len(overrides)} overrides: {[(hex(a), hex(b), hex(c)) for a, b, c in overrides[:20]]}", file=sys.stderr)
rows.sort()
print("/* Generated by tools/gen/gen_chunk_info.py from TmForeverFixed.exe 2.11.26")
print("   (every class's GetChunkInfo, emulated). Do not edit.")
print("   bit 0: parsed by Chunk(); bit 4: stored skippable. */")
print("#ifndef TMUF_CHUNK_INFO_TABLE_H")
print("#define TMUF_CHUNK_INFO_TABLE_H")
print()
print("#include <stdint.h>")
print()
print(f"static const uint32_t TMUF_CHUNK_INFO[{len(rows)}][2] = {{")
for chunk, info, cls in rows:
    print(f"  {{0x{chunk:08x}, 0x{info:08x}}}, /* {cls} */")
print("};")
print()
print("/* Classes answering differently for an ancestor's chunk: class, chunk, flags. */")
print(f"static const uint32_t TMUF_CHUNK_INFO_OVERRIDE[{len(overrides)}][3] = {{")
for cid, chunk, info in sorted(overrides):
    print(f"  {{0x{cid:08x}, 0x{chunk:08x}, 0x{info:08x}}},")
print("};")
print()
print("#endif")
print(f"# {len(rows)} known chunks, {len(failed)} emulation failures", file=sys.stderr)
