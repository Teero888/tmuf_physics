#!/usr/bin/env python3
"""Generate src/common/tuning_schema.h: field layout of every
CSceneVehicleCarTuning chunk (R real, N natural, B bool, O node reference,
F float array, I lookback id).

  gen_tuning_schema.py SCHEMA_H IDS_H > src/common/tuning_schema.h
"""
import re
import sys

schema = open(sys.argv[1]).read()
ids = open(sys.argv[2]).read()
block = ids[ids.index("enum class VehicleTuningChunkId"):]
block = block[:block.index("};")]
values = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"(\w+)\s*=\s*0x([0-9a-fA-F]+)u", block)}
kinds = {"Real": "R", "Natural": "N", "Boolean": "B", "NodRef": "O", "FloatArray": "F", "CmwId": "I"}
fields = {}
for m in re.finditer(r"Fields_(\w+)\[\]\s*=\s*\{([^}]*)\}", schema):
    fields[m.group(1)] = "".join(kinds[k] for k in re.findall(r"F::(\w+)", m.group(2)))
rows = []
for m in re.finditer(r"SchemaFor\(VehicleTuningChunkId::(\w+),\s*Fields_(\w+)\)", schema):
    rows.append((values[m.group(1)], fields[m.group(2)], m.group(1)))
# Legacy chunks with fixed layouts (static_solid_archive_vehicle_tuning_reader.cpp).
LEGACY = {
    "LegacyBodyTuningThreeReals": "RRR", "LegacyGroundFeedbackFourReals": "RRRR",
    "M6ReverseAndTurboImpulse": "RR", "AirborneTorque": "RR", "LegacySolidInertiaNatural": "N",
    "LegacyWheelForceSingleReal": "R", "LegacyForceModelNineReals": "RRRRRRRRR",
    "LegacyForceModelFiveRealsA": "RRRRR", "LegacyForceModelFiveRealsB": "RRRRR",
    "ForceModelTwoRealsA": "RR", "LegacyForceModelTwoRealsB": "RR",
    "ContactImpulseSingleRealA": "R", "ContactImpulseSingleRealB": "R",
    "LegacyContactImpulseSixReals": "RRRRRR", "LegacyAirControlSingleReal": "R",
    "LegacyAirControlTwoReals": "RR", "LegacyM5AccelThreeReals": "RRR", "TurboDuration": "N",
    "Model4AuxCurveRef": "O", "Model5AuxCurveRefA": "O", "Model5AuxCurveRefB": "O",
    "LegacyM6SlipFiveReals": "RRRRR", "WaterResponseAuxCurveRef": "O", "ForceFeedbackDivisorLegacy": "RR",
    "M6ReverseBurnoutForceThresholdLegacy": "RRO", "M6EmptyLegacyPayload": "",
    "M6CompositeBurnoutPayload": "RROORRRRRRRRRNRRNRRRROORRRRRRFFFN",
    "M6FloatBufferSet": "FFFF", "M6FloatBufferLegacySingle": "F",
    "M6Mat6AuxSlideRealA": "R", "M6Mat6AuxSlideRealB": "R", "M6Mat6AuxSlideRealC": "R", "M6Mat6AuxSlideRealD": "R",
}
have = {r[0] for r in rows}
for name, f in LEGACY.items():
    if values[name] not in have:
        rows.append((values[name], f, name))
rows.sort()
print("/* Generated by tools/gen/gen_tuning_schema.py. Do not edit.")
print("   Field kinds: R real, N natural, B bool, O node ref, F float array,")
print("   I lookback id. */")
print("#ifndef TMUF_TUNING_SCHEMA_H")
print("#define TMUF_TUNING_SCHEMA_H")
print()
print("#include <stdint.h>")
print()
print("typedef struct tmuf_tuning_chunk_schema {")
print("  uint32_t chunk_id;")
print("  const char *fields;")
print("  const char *name;")
print("} tmuf_tuning_chunk_schema;")
print()
print(f"static const tmuf_tuning_chunk_schema TMUF_TUNING_SCHEMA[{len(rows)}] = {{")
for cid, f, name in rows:
    print(f'  {{0x{cid:08x}, "{f}", "{name}"}},')
print("};")
print()
print("#endif")
