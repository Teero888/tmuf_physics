#!/usr/bin/env python3
"""Generate src/common/class_id_table.h from the game's
CMwDeprecated::WrapClassId (0x935d50, archive id -> current id) and
CMwDeprecated::UnWrapClassId (0x936660, current id -> archive id) in TMUF
2.11.26. Both are compare/branch trees; each is run by a tiny interpreter
for every constant it compares against.

  gen_class_id_table.py TmForever.exe > src/common/class_id_table.h
"""
import sys

import capstone
import pefile

FUNCS = [("TMUF_WRAP_CLASS_ID", 0x935d50, "archive id -> current id"),
         ("TMUF_UNWRAP_CLASS_ID", 0x936660, "current id -> archive id")]

pe = pefile.PE(sys.argv[1], fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def load(func):
    ins = {}
    for i in md.disasm(pe.get_data(func - base, 0x1000), func):
        ins[i.address] = i
        if i.mnemonic == "int3":
            break
    return ins


def run(ins, func, eax):
    pc, flags = func, None
    for _ in range(10000):
        i = ins[pc]
        m, ops = i.mnemonic, i.op_str
        nxt = pc + i.size
        if m == "mov" and ops.startswith("eax, dword ptr [esp + 4]"):
            pass
        elif m == "mov" and ops.startswith("eax, 0x"):
            eax = int(ops.split(", ")[1], 16)
        elif m == "mov" and ops == "eax, 0":
            eax = 0
        elif m == "cmp" and ops.startswith("eax, "):
            k = int(ops.split(", ")[1], 16)
            flags = (eax > k) - (eax < k)
        elif m in ("ja", "je", "jne", "jb", "jae", "jbe", "jmp"):
            t = int(ops, 16)
            take = {"ja": flags > 0, "je": flags == 0, "jne": flags != 0, "jb": flags < 0,
                    "jae": flags >= 0, "jbe": flags <= 0, "jmp": True}[m]
            if take:
                nxt = t
        elif m == "ret":
            return eax
        else:
            raise SystemExit(f"unhandled {m} {ops} at {pc:x}")
        pc = nxt
    raise SystemExit("no ret")


print("/* Generated by tools/gen/gen_class_id_table.py from TmForever.exe 2.11.26")
print("   (CMwDeprecated::WrapClassId / UnWrapClassId). Do not edit. */")
print("#ifndef TMUF_CLASS_ID_TABLE_H")
print("#define TMUF_CLASS_ID_TABLE_H")
print()
print("#include <stdint.h>")
for table, func, what in FUNCS:
    ins = load(func)
    keys = sorted({int(i.op_str.split(", ")[1], 16) for i in ins.values() if i.mnemonic == "cmp"})
    pairs = [(k, run(ins, func, k)) for k in keys]
    pairs = [(k, v) for k, v in pairs if k != v]
    assert run(ins, func, 0x12345678) == 0x12345678  # default: unchanged
    print()
    print(f"/* {what}; sorted by key, ids not listed map to themselves. */")
    print(f"static const uint32_t {table}[{len(pairs)}][2] = {{")
    for k, v in pairs:
        print(f"  {{0x{k:08x}, 0x{v:08x}}},")
    print("};")
print()
print("#endif")
