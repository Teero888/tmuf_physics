#!/usr/bin/env python3
"""Generate src/common/class_tree.h: every engine class (id, parent id, name)
from the CMwClassInfo dynamic initializers of TmForeverFixed.exe, located via
its PDB. Each initializer is
    push new_func; push name; push parent_info; push class_id
    mov ecx, class_info; call CMwClassInfo::CMwClassInfo

  gen_class_tree.py TmForeverFixed.exe TmForeverFixed.pdb > src/common/class_tree.h
"""
import os
import sys

import capstone
import pefile

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "oracle"))
from sigmap import load_publics  # noqa: E402

pe = pefile.PE(sys.argv[1], fast_load=True)
base = pe.OPTIONAL_HEADER.ImageBase
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def cstring(va):
    data = pe.get_data(va - base, 128)
    return data.split(b"\0", 1)[0].decode("latin-1")


infos = {}  # class_info address -> (id, parent_info, name)
for name, locs in load_publics(sys.argv[2]).items():
    if "dynamic_initializer_for_" not in name or "m_MwClassInfo_" not in name:
        continue
    sec, off = locs[0]
    va = base + pe.sections[sec - 1].VirtualAddress + off
    pushes, ecx = [], None
    for ins in md.disasm(pe.get_data(va - base, 64), va):
        if ins.mnemonic == "push" and ins.op_str.startswith("0x"):
            pushes.append(int(ins.op_str, 16))
        elif ins.mnemonic == "push":
            pushes.append(0)
        elif ins.mnemonic == "mov" and ins.op_str.startswith("ecx, 0x"):
            ecx = int(ins.op_str.split(", ")[1], 16)
        elif ins.mnemonic == "call":
            break
    if ecx is None or len(pushes) < 4:
        continue
    class_id, parent, name_ptr = pushes[-1], pushes[-2], pushes[-3]
    infos[ecx] = (class_id, parent, cstring(name_ptr) if name_ptr else "")

rows = []
for addr, (cid, parent, name) in infos.items():
    pid = infos[parent][0] if parent in infos else 0
    rows.append((cid, pid, name))
rows.sort()
print("/* Generated by tools/gen/gen_class_tree.py from TmForeverFixed.exe 2.11.26")
print("   (CMwClassInfo initializers). Do not edit. */")
print("#ifndef TMUF_CLASS_TREE_H")
print("#define TMUF_CLASS_TREE_H")
print()
print("#include <stdint.h>")
print()
print("typedef struct tmuf_class_info {")
print("  uint32_t id, parent;")
print("  const char *name;")
print("} tmuf_class_info;")
print()
print("/* Sorted by id. parent is 0 for the root. */")
print(f"static const tmuf_class_info TMUF_CLASSES[{len(rows)}] = {{")
for cid, pid, name in rows:
    print(f'  {{0x{cid:08x}, 0x{pid:08x}, "{name}"}},')
print("};")
print()
print("#endif")
