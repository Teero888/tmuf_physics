#!/usr/bin/env python3
"""Generate src/common/blowfish_tables.h: Blowfish P-array and S-boxes, the
fractional hex digits of pi (Machin's formula, pure integer arithmetic)."""
import sys

WORDS = 18 + 4 * 256
digits = WORDS * 8 + 16
scale = 16 ** digits


def arctan_inv(x):
    total, term, n, sign = 0, scale // x, 1, 1
    x2 = x * x
    while term:
        total += sign * (term // n)
        term //= x2
        n += 2
        sign = -sign
    return total


pi = 16 * arctan_inv(5) - 4 * arctan_inv(239)
frac = pi - 3 * scale
hexstr = format(frac, "x").rjust(digits, "0")
words = [int(hexstr[i * 8:i * 8 + 8], 16) for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B and words[18] == 0xD1310BA6

out = ["/* Generated by tools/gen/gen_blowfish_tables.py. Do not edit. */",
       "#ifndef TMUF_BLOWFISH_TABLES_H", "#define TMUF_BLOWFISH_TABLES_H", "",
       "#include <stdint.h>", "",
       "static const uint32_t BLOWFISH_P_INIT[18] = {"]
for i in range(0, 18, 6):
    out.append("  " + ", ".join(f"0x{w:08x}" for w in words[i:i + 6]) + ",")
out.append("};")
out.append("")
out.append("static const uint32_t BLOWFISH_S_INIT[4][256] = {")
for b in range(4):
    out.append("  {")
    sbox = words[18 + b * 256:18 + (b + 1) * 256]
    for i in range(0, 256, 6):
        out.append("    " + ", ".join(f"0x{w:08x}" for w in sbox[i:i + 6]) + ",")
    out.append("  },")
out.append("};")
out.append("")
out.append("#endif")
sys.stdout.write("\n".join(out) + "\n")
